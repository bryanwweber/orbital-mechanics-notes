"""Regenerate launch-sites.js with uv run python generate_launch_azimuths.py."""

import json
from pathlib import Path

from pyproj import Geod

GEOD = Geod(ellps="WGS84")
SITES = {
    "kennedy": (
        "Launch Pad 39A, Kennedy Space Center",
        28.626407252553207,
        -80.6204675295687,
        (35, 120),
    ),
    "vandenberg": (
        "Vandenberg Space Force Base",
        34.58275238653322,
        -120.62596633922566,
        (158, 201),
    ),
}


def ray(lat, lon, azimuth):
    """Sample a geodesic from the launch site at 50 km intervals."""
    points = [[lat, lon]]
    for distance in range(50_000, 2_500_001, 50_000):
        dest_lon, dest_lat, _ = GEOD.fwd(lon, lat, azimuth, distance)
        points.append([round(dest_lat, 6), round(dest_lon, 6)])
    return points


def main():
    records = []
    for key, (name, lat, lon, limits) in SITES.items():
        north = ray(lat, lon, 0)
        south = ray(lat, lon, 180)
        site = {
            "name": name,
            "location": [lat, lon],
            "limits": limits,
            "meridian": [*reversed(south[1:]), *north],
            "rays": [ray(lat, lon, azimuth) for azimuth in limits],
        }
        records.append(
            f"  {key}: {json.dumps(site, ensure_ascii=False, separators=(',', ':'))},"
        )
    output = "// Generated by generate_launch_azimuths.py.\nexport const sites = {\n"
    Path(__file__).with_name("launch-sites.js").write_text(
        output + "\n".join(records) + "\n};\n", encoding="utf-8"
    )


if __name__ == "__main__":
    main()
