import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";

const output = "assets/js/orbital-three";
const packages = {};
const project = JSON.parse(await readFile("package.json", "utf8"));
await mkdir(output, { recursive: true });
await mkdir("assets/fonts/katex", { recursive: true });
for (const filename of ['KaTeX_Main-Regular.ttf', 'KaTeX_Math-Italic.ttf', 'LICENSE']) {
  await writeFile(`assets/fonts/katex/${filename}`, await readFile(`assets-src/fonts/katex/${filename}`));
}
for (const name of ["three", "lil-gui"]) {
  const metadata = JSON.parse(await readFile(`node_modules/${name}/package.json`, "utf8"));
  if (project.dependencies[name] !== metadata.version) {
    throw new Error(`${name} must match the exact version in package.json; run bun install --frozen-lockfile.`);
  }
  packages[name] = metadata.version;
  const license = name === "lil-gui" ? "LICENSE.md" : "LICENSE";
  await writeFile(`${output}/${name}.LICENSE.txt`, await readFile(`node_modules/${name}/${license}`));
}
const result = await Bun.build({
  entrypoints: ["assets-src/orbital-three.mjs", "assets-src/math-fonts.mjs"],
  outdir: output,
  naming: "[name].js",
  target: "browser",
  format: "esm",
  minify: true,
  banner: `// Generated by bun run build:threejs. Three.js ${packages.three}; lil-gui ${packages["lil-gui"]}. See adjacent license files.`,
});
if (!result.success) throw new AggregateError(result.logs, "Three.js bundle build failed");
const bundle = await readFile(`${output}/orbital-three.js`);
await writeFile(`${output}/provenance.json`, `${JSON.stringify({
  generatedBy: "bun run build:threejs",
  bun: Bun.version,
  packages,
  upstream: { three: "https://github.com/mrdoob/three.js", "lil-gui": "https://github.com/georgealways/lil-gui" },
  sha256: createHash("sha256").update(bundle).digest("hex"),
}, null, 2)}\n`);
console.log(`Built Three.js ${packages.three} + lil-gui ${packages["lil-gui"]}: ${bundle.length} bytes`);
