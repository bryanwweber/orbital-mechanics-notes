import assert from "node:assert/strict";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

// These published paths changed during the Jupyter Book -> MyST migration.
const aliases = {
  "the-n-body-problem/Equations-of-Motion-CR3BP.html": "the-n-body-problem.equations-of-motion-cr3bp",
  "the-n-body-problem/Lagrange-points-example.html": "the-n-body-problem.lagrange-points-example",
  "interplanetary-maneuvers/planetary-depahture-trajectory.html": "interplanetary-maneuvers.planetary-departure-trajectory",
};
const marker = "<!-- Generated by scripts/book-redirects.mjs -->";
const escapeHtml = (value) => value.replaceAll("&", "&amp;").replaceAll('"', "&quot;")
  .replaceAll("<", "&lt;").replaceAll(">", "&gt;");

function redirectPage(target, canonical, anchors) {
  // Use JavaScript to preserve query strings and translate old Sphinx equation
  // fragments. The immediate meta refresh also works without JavaScript.
  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  ${marker}
  <title>Page moved</title>
  <link rel="canonical" href="${escapeHtml(canonical)}">
  <script>
    const target = ${JSON.stringify(target)};
    const anchors = ${JSON.stringify(anchors)};
    let fragment = window.location.hash.slice(1);
    try { fragment = decodeURIComponent(fragment); } catch {}
    const anchor = Object.hasOwn(anchors, fragment) ? anchors[fragment] : fragment;
    const hash = fragment ? "#" + encodeURIComponent(anchor) : "";
    window.location.replace(target + window.location.search + hash);
  </script>
  <meta http-equiv="refresh" content="0; url=${escapeHtml(target)}">
</head>
<body>
  <p>This page has moved. <a href="${escapeHtml(target)}">Continue to the page</a>.</p>
</body>
</html>
`;
}

const buildRoot = process.argv[2] ?? "_build";
const config = JSON.parse(await readFile(path.join(buildRoot, "site/config.json"), "utf8"));
const project = config.projects[0];
const slugs = [project.index, ...project.pages.filter((page) => page.slug).map((page) => page.slug)];
const pages = new Map();
const redirects = new Map();
function addRedirect(file, slug) {
  assert.match(file, /^[a-zA-Z0-9_/-]+\.html$/, `Unexpected legacy path: ${file}`);
  assert.ok(file !== "index.html", "The home page must never become a redirect");
  assert.ok(!redirects.has(file) || redirects.get(file) === slug, `Conflicting redirect: ${file}`);
  redirects.set(file, slug);
}

for (const slug of slugs) {
  const page = JSON.parse(await readFile(path.join(buildRoot, "site/content", `${slug}.json`), "utf8"));
  const route = slug === project.index ? "" : slug.replace(/\.index$/, "").replaceAll(".", "/");
  const html = await readFile(path.join(buildRoot, "html", route, "index.html"), "utf8");
  assert.match(html, /<h1[\s>]/, `Redirect destination must contain its page: ${route || "/"}`);
  const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map((match) => match[1]);
  const anchors = Object.fromEntries(ids.map((id) => [`equation-${id}`, id]));
  // The former misspelled departure page has corrected labels in its replacement.
  for (const id of ids) {
    if (id.includes("departure")) {
      const oldId = id.replaceAll("departure", "depahture");
      anchors[oldId] = id;
      anchors[`equation-${oldId}`] = id;
    }
  }
  pages.set(slug, { route, anchors });
  // Derive legacy filenames from source locations, retaining original case.
  assert.match(page.location, /^\/chapters\/.+\.(md|ipynb)$/, `Unexpected source: ${page.location}`);
  addRedirect(page.location.replace(/^\/chapters\//, "").replace(/\.(md|ipynb)$/, ".html"), slug);
  if (route) addRedirect(`${route}.html`, slug);
}
for (const [file, slug] of Object.entries(aliases)) {
  assert.ok(pages.has(slug), `Missing destination for published URL: ${file}`);
  addRedirect(file, slug);
}

// Validate the complete mapping before writing any files.
const output = [];
for (const [file, slug] of redirects) {
  const { route, anchors } = pages.get(slug);
  const relative = path.posix.relative(path.posix.dirname(file), route || ".");
  const target = relative ? `${relative}/` : "./";
  const canonical = `https://orbital-mechanics.space/${route}${route ? "/" : ""}`;
  const destination = path.join(buildRoot, "html", file);
  try {
    const existing = await readFile(destination, "utf8");
    assert.ok(existing.includes(marker), `Refusing to overwrite an existing page: ${file}`);
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  output.push({ destination, html: redirectPage(target, canonical, anchors) });
}
for (const { destination, html } of output) {
  await mkdir(path.dirname(destination), { recursive: true });
  await writeFile(destination, html);
}
console.log(`Generated ${redirects.size} legacy HTML redirects to ${pages.size} book pages.`);
